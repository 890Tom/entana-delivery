import {
  Body,
  applyDecorators,
  Controller,
  Header,
  HttpCode,
  Post,
  Res,
  UseGuards,
} from "@nestjs/common";
import {
  ApiBody,
  ApiCreatedResponse,
  ApiHeader,
  ApiOperation,
  ApiResponse,
  ApiTags,
} from "@nestjs/swagger";
import { createOrderResponseSchema, problemDetailsSchema } from "@entana/contracts";
import type { CreateOrderRequest, CreateOrderResponse } from "@entana/contracts";
import type { Response } from "express";
import { CREATE_ORDER_BODY_SCHEMA } from "./order-openapi.js";
import { JsonContentTypeGuard } from "./json-content-type.guard.js";
import {
  CreateOrderBodyPipe,
  IDEMPOTENCY_KEY_HEADER,
  idempotencyKeyHeader,
  IdempotencyKeyPipe,
} from "./order-validation.js";
import { OrdersService } from "./orders.service.js";

const REPLAY_HEADER = "Idempotent-Replayed";

// Obviously fake: nothing here looks like a real phone number, place or token.
const EXAMPLE_REQUEST = {
  phone: "000 00 000 00",
  trackingToken: "A".repeat(43),
  contactName: "Example Customer",
  landmarkText: "Example landmark",
  location: { lat: 0, lng: 0 },
  items: [{ productId: "00000000-0000-4000-8000-000000000001", quantity: 1 }],
};

const PROBLEM_RESPONSES = [
  [
    400,
    "Invalid body or Idempotency-Key header. Lists the invalid fields only, never their values.",
  ],
  [403, "This order cannot be placed. The same answer for every refusal of this kind."],
  [
    409,
    "The idempotency key was already used for a different request. The same answer for every conflict.",
  ],
  [413, "The body is larger than the limit."],
  [415, "The content type is not application/json."],
  [
    422,
    "A product is unknown, inactive or unavailable (listed by the ids the client sent), or the order is too large.",
  ],
  [
    429,
    "Too many requests, from this address or for this phone number. The same body for both, with Retry-After.",
  ],
  [500, "An unexpected error. The body is generic."],
  [503, "The database is unreachable."],
] as const;

const documentProblems = (): MethodDecorator =>
  applyDecorators(
    ...PROBLEM_RESPONSES.map(([status, description]) =>
      ApiResponse({ status, description, standardSchema: problemDetailsSchema }),
    ),
  );

@ApiTags("orders")
@Controller({ path: "orders", version: "1" })
export class OrdersController {
  constructor(private readonly ordersService: OrdersService) {}

  @Post()
  @HttpCode(201)
  @UseGuards(JsonContentTypeGuard)
  @Header("Cache-Control", "no-store")
  @ApiOperation({
    summary: "Create an order",
    description:
      "Public. Idempotent: the same Idempotency-Key with the same body returns the same answer " +
      "and Idempotent-Replayed: true. The client generates the key and the tracking token.",
    operationId: "createOrder",
  })
  @ApiHeader({
    name: IDEMPOTENCY_KEY_HEADER,
    required: true,
    description: "A uuid generated by the client, once per order.",
    schema: { type: "string", format: "uuid", example: "00000000-0000-4000-8000-000000000000" },
  })
  @ApiBody({
    schema: CREATE_ORDER_BODY_SCHEMA,
    examples: { fake: { summary: "Fake values", value: EXAMPLE_REQUEST } },
  })
  @ApiCreatedResponse({
    description: "The order was created, or this is a replay (Idempotent-Replayed: true).",
    standardSchema: createOrderResponseSchema,
    headers: {
      [REPLAY_HEADER]: { description: "true on a replay.", schema: { type: "string" } },
    },
  })
  @documentProblems()
  async create(
    @idempotencyKeyHeader(IdempotencyKeyPipe) idempotencyKey: string,
    @Body(CreateOrderBodyPipe) body: CreateOrderRequest,
    @Res({ passthrough: true }) response: Response,
  ): Promise<CreateOrderResponse> {
    const result = await this.ordersService.createOrder(body, idempotencyKey);
    // The service decides what a replay is; the controller only reports it.
    if (result.replayed) {
      response.setHeader(REPLAY_HEADER, "true");
    }
    return result.response;
  }
}
